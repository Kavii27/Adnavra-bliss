const AVAILABLE_SLUGS = new Set<string>(manifest.available);

/** lowercase, punctuation -> spaces, collapsed. "Cut & Blow-dry!" -> "cut blow dry" */
export function normalizeServiceName(name: string): string {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

type Match = { rule: ServiceImageRule; position: number; length: number };

function findBestMatch(normalized: string, rules: ServiceImageRule[]): Match | null {
  const haystack = " " + normalized;
  let best: Match | null = null;
  for (const rule of rules) {
    for (const kw of rule.keywords) {
      const idx = haystack.indexOf(" " + kw);
      if (idx === -1) continue;
      // Earliest word in the name wins; on a tie the longer (more specific) keyword wins.
      if (
        !best ||
        idx < best.position ||
        (idx === best.position && kw.length > best.length)
      ) {
        best = { rule, position: idx, length: kw.length };
      }
    }
  }
  return best;
}

/** Best-guess catalog slug for a service, or null if nothing matches. */
export function matchServiceSlug(
  name: string,
  category: string | null | undefined,
): { slug: string; category: string } | null {
  const normalized = normalizeServiceName(name ?? "");
  if (!normalized) return null;

  // 1) Same category first (most accurate).
  if (category && KNOWN_CATEGORIES.has(category)) {
    const inCategory = findBestMatch(
      normalized,
      SERVICE_IMAGE_RULES.filter((r) => r.category === category),
    );
    if (inCategory) return { slug: inCategory.rule.slug, category: inCategory.rule.category };
  }

  // 2) Any category (handles missing / wrong category).
  const anywhere = findBestMatch(normalized, SERVICE_IMAGE_RULES);
  return anywhere ? { slug: anywhere.rule.slug, category: anywhere.rule.category } : null;
}

function specificPath(category: string, slug: string): string {
  return `${SERVICE_IMAGE_ROOT}/${category}/${slug}.${SERVICE_IMAGE_EXT}`;
}

function categoryPath(category: string): string {
  return `${SERVICE_IMAGE_ROOT}/_category/${category}.${SERVICE_IMAGE_EXT}`;
}

const DEFAULT_IMAGE = `${SERVICE_IMAGE_ROOT}/_category/default.${SERVICE_IMAGE_EXT}`;

/**
 * Ordered list of image URLs to try, best first. The UI walks this list if an
 * image fails to load, so a missing file never shows a broken picture.
 */
export function resolveServiceImageCandidates(
  name: string,
  category: string | null | undefined,
): string[] {
  const candidates: string[] = [];

  const match = matchServiceSlug(name, category);
  if (match && AVAILABLE_SLUGS.has(match.slug)) {
    candidates.push(specificPath(match.category, match.slug));
  }

  // Prefer the service's own category for the fallback; else the matched one.
  const fallbackCategory =
    category && KNOWN_CATEGORIES.has(category) ? category : match?.category ?? null;
  if (fallbackCategory) candidates.push(categoryPath(fallbackCategory));

  candidates.push(DEFAULT_IMAGE);
  return candidates;
}

/** Single best image URL for a service. */
export function resolveServiceImage(name: string, category: string | null | undefined): string {
  return resolveServiceImageCandidates(name, category)[0];
}
