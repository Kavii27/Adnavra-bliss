/**
 * Service image resolver (interim, no database changes).
 *
 * Works out which picture to show for a service at display time, using only
 * the service's existing `name` and `category`. Many salons offering the same
 * service therefore share ONE image file on disk.
 *
 * Resolution order (see resolveServiceImageCandidates):
 *   1. Specific image   /service-images/<category>/<slug>.webp   (only if that file exists)
 *   2. Category image   /service-images/_category/<category>.webp
 *   3. Default image    /service-images/_category/default.webp
 *
 * Which specific images exist is listed in `service-images.manifest.json`,
 * regenerated by `node scripts/optimize-service-images.mjs`.
 *
 * Later, when the database ServiceTemplate plan ships, this rule list becomes
 * the seed / backfill matcher and this helper stays as the fallback.
 */
